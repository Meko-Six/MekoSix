#!/usr/bin/env python3
"""Generate paste-ready Spectra accordion details from projects.json."""

from __future__ import annotations

import json
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
PREVIEW = SITE / "preview"


def esc(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def action(project: dict) -> str:
    label = esc(project.get("download_label") or "Download")
    url = project.get("download") or ""

    if project.get("download_pending"):
        if project.get("kind") == "font":
            return '<span class="m6-btn m6-btn-pending">Licence pending</span>'
        return '<span class="m6-btn m6-btn-pending">Publishes after notarization</span>'

    attrs = ['class="m6-btn"', f'href="{esc(url)}"']
    if project.get("kind") == "app" and project.get("local_download"):
        attrs.append("download")
    if project.get("external"):
        attrs.extend(['target="_blank"', 'rel="noopener"'])
    return f'<a {" ".join(attrs)}>{label}</a>'


def secondary(project: dict) -> str:
    item = project.get("secondary")
    if not item or item.get("pending"):
        return ""
    url = esc(item.get("wp_url") or item.get("url", "#"))
    external = ' target="_blank" rel="noopener"' if url.startswith("http") else ""
    return f'<a class="m6-link" href="{url}"{external}>{esc(item["label"])}</a>'


def snippet(project: dict, accent: str) -> str:
    image_note = ""
    if project.get("wp_image"):
        image = (
            '<figure class="m6-figure">'
            f'<img class="m6-shot" src="{esc(project["wp_image"])}" '
            f'alt="{esc(project.get("image_alt", project["title"]))}" loading="lazy">'
            "</figure>"
        )
    else:
        image = ""
        image_note = (
            f'  <!-- TODO image: {esc(project.get("wp_image_note") or "add a screenshot")} -->'
        )

    image_lines = [line for line in (image_note, f"  {image}" if image else "") if line]
    image_markup = ("\n".join(image_lines) + "\n") if image_lines else ""

    secondary_markup = secondary(project)
    secondary_line = f"\n  {secondary_markup}" if secondary_markup else ""

    return (
        f"<!-- {project['id']} -->\n"
        '<div class="m6-project" '
        f'style="--m6-accent: {esc(accent)}">\n'
        f'  <span class="m6-anchor" id="{esc(project.get("anchor", project["id"]))}"></span>\n'
        f"{image_markup}"
        f'  <p class="m6-description">{esc(project["description"])}</p>\n'
        f'  <p class="m6-meta">{esc(" · ".join(project.get("meta", [])))}</p>\n'
        f'  <p class="m6-actions">{action(project)}{secondary_line}</p>\n'
        f'  <p class="m6-note">{esc(project.get("note", ""))}</p>\n'
        "</div>\n"
    )


def main() -> None:
    data = json.loads((SITE / "projects.json").read_text(encoding="utf-8"))
    blocks: list[str] = [
        "<!-- Generated by site/scripts/build_wordpress.py from projects.json. -->",
        "<!-- Paste one block into the matching Spectra accordion details, or use a Custom HTML block. -->",
        "",
    ]

    for collection in data["collections"]:
        blocks.append(f"<!-- ===== {collection['title']} ===== -->")
        for project in collection["projects"]:
            blocks.append(snippet(project, collection["accent"]))

    output = SITE / "content" / "wordpress-snippets.html"
    output.write_text("\n".join(blocks), encoding="utf-8")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
