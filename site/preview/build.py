#!/usr/bin/env python3
"""Generate preview/projects.js from site/projects.json."""

from __future__ import annotations

import json
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
PREVIEW = SITE / "preview"


def main() -> None:
    data = json.loads((SITE / "projects.json").read_text(encoding="utf-8"))
    missing: list[str] = []
    for collection in data["collections"]:
        for project in [collection, *collection["projects"]]:
            image = project.get("image")
            if image and not (PREVIEW / image).exists():
                missing.append(image)

    payload = json.dumps(data, ensure_ascii=False, indent=2)
    (PREVIEW / "projects.js").write_text(
        "/* Generated by build.py from ../projects.json — do not edit by hand. */\n"
        f"window.PROJECTS = {payload};\n",
        encoding="utf-8",
    )

    count = sum(len(c["projects"]) for c in data["collections"])
    print(f"wrote preview/projects.js ({len(data['collections'])} collections, {count} projects)")
    if missing:
        print("missing preview images:")
        for image in missing:
            print(f"  - {image}")
    else:
        print("all preview images present")


if __name__ == "__main__":
    main()
